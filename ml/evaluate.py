# Reports
# ---------------------------------------------------------------------------


def _fmt(value):
    return "-" if value is None else (f"{value:.3f}" if isinstance(value, float) else str(value))


def render_markdown(report: dict) -> str:
    world = report["world"]
    split = report["split"]
    results = report["results"]
    lines = [
        "# Model evaluation - synthetic world only",
        "",
        f"> {report['honesty']}",
        "",
        f"Dataset: {world['bookings']} bookings over {world['weeks']} weeks, "
        f"seed {world['seed']} - regenerate it exactly with "
        f"`python -m ml.synth --bookings {world['bookings']} --seed {world['seed']}`. "
        f"Scored on Python {report.get('environment', {}).get('python', '?')}, "
        f"scikit-learn {report.get('environment', {}).get('scikit_learn') or 'not installed'} "
        f"- the dataset is byte-reproducible from its seed, but sklearn numbers "
        f"can drift across library releases.",
        "",
        f"Time split at {split['cut_date']}: {split['train']} bookings train, "
        f"{split['test']} test, {split['dropped_straddling_bookings']} dropped "
        f"because a disruption episode straddled the boundary "
        f"({split['train_episodes']} train episodes, {split['test_episodes']} "
        f"test episodes, zero shared - asserted, not assumed).",
        "",
    ]

    lines += ["## Action model - reroute / hold / no-action", "",
              "| backend | accuracy | macro-F1 |", "|---|---|---|"]
    for name, r in results["action"].items():
        if "skipped" in r:
            lines.append(f"| {name} | skipped | skipped |")
        else:
            lines.append(f"| {name} | {_fmt(r['accuracy'])} | {_fmt(r['macro_f1'])} |")
    best = _best(results["action"], "accuracy", higher=True)
    if best:
        lines += ["", f"Confusion table for `{best}` (rows = truth, columns = predicted):", ""]
        table = results["action"][best]["confusion"]
        lines.append("| truth \\ predicted | " + " | ".join(models.ACTION_LABELS) + " |")
        lines.append("|---|" + "---|" * len(models.ACTION_LABELS))
        for truth in models.ACTION_LABELS:
            lines.append(f"| {truth} | " + " | ".join(
                str(table[truth][p]) for p in models.ACTION_LABELS) + " |")
    lines.append("")

    lines += ["## Delay model - days late on the do-nothing path", "",
              "| backend | MAE (days) | P90 abs error (days) |", "|---|---|---|"]
    for name, r in results["delay"].items():
        if "skipped" in r:
            lines.append(f"| {name} | skipped | skipped |")
        else:
            lines.append(f"| {name} | {_fmt(r['mae_days'])} | {_fmt(r['p90_abs_error_days'])} |")
    lines.append("")

    lines += ["## Breach model - probability the deadline breaks", "",
              "| backend | ROC-AUC | Brier |", "|---|---|---|"]
    for name, r in results["breach"].items():
        if "skipped" in r:
            lines.append(f"| {name} | skipped | skipped |")
        else:
            lines.append(f"| {name} | {_fmt(r['roc_auc'])} | {_fmt(r['brier'])} |")
    lines.append("")

    skipped = sorted({name for task in results.values()
                      for name, r in task.items() if "skipped" in r})
    if skipped:
        lines += ["## Skipped backends", ""]
        seen = set()
        for task in results.values():
            for name, r in task.items():
                if "skipped" in r and name not in seen:
                    seen.add(name)
                    lines.append(f"**{name}**\n")
                    lines += [f"    {line}" for line in r["skipped"].splitlines()]
                    lines.append("")

    lines += _plain_language_reading(results)
    return "\n".join(lines) + "\n"


def _best(task_results, metric, higher=True):
    scored = {n: r[metric] for n, r in task_results.items()
              if "skipped" not in r and r.get(metric) is not None}
    if not scored:
        return None
    return (max if higher else min)(scored, key=scored.get)


def _plain_language_reading(results) -> list[str]:
    """The closing section, written for the repo owner, who does not code.

    Every NUMBER and every direction-of-error claim below is computed from the
    results dict, so those can never contradict the tables above. The causal
    explanations (why the rules engine trails, where the noise comes from) are
    descriptions of the current generator calibration - regenerate the world
    with different NOISE/TYPE_PARAMS and reread them before trusting them."""
    lines = ["## What this means, in plain language", ""]

    action = results["action"]
    if "skipped" not in action.get("gbm", {"skipped": True}) and "skipped" not in action.get("majority", {"skipped": True}):
        gbm = action["gbm"]["accuracy"]
        majority = action["majority"]["accuracy"]
        lines.append(
            f"On the reroute/hold/do-nothing call, always answering \"do nothing\" "
            f"is right {majority:.0%} of the time in this simulated world - most "
            f"bookings are fine, there as here. The best trained model gets "
            f"{gbm:.0%}. The gap between those two numbers is what learning is "
            f"actually worth on this task. The shortfall from 100% is by "
            f"construction: the generator injects noise no observer is shown - "
            f"how hard a storm bites, whether a strike settles tomorrow - so a "
            f"model scoring near-perfectly here would be a bug, not a triumph.")
        if "skipped" not in action.get("rules", {"skipped": True}):
            rules = action["rules"]["accuracy"]
            table = action["rules"]["confusion"]
            acted = [l for l in models.ACTION_LABELS if l != "no-action"]
            # Which way the rules engine is wrong is measured, not asserted -
            # a report that described a direction the table contradicts would
            # be this repo's hard-coded "live" chip all over again.
            over_alert = sum(table["no-action"][p] for p in acted)
            under_alert = sum(table[t]["no-action"] for t in acted)
            caught = sum(table[t][p] for t in acted for p in acted)
            missed = under_alert
            lines.append("")
            lines.append(
                f"The rules engine the product actually ships scores {rules:.0%} "
                f"here. It asks one timing question this harness surfaced the "
                f"need for - whether an episode will still be standing when the "
                f"vessel actually reaches the chokepoint (timing_factor in "
                f"src/route_advisor.py, asked only when the record carries the "
                f"facts to answer it). What remains of the gap is everything "
                f"else the learners weigh that a fixed rule cannot: how hard "
                f"each episode type tends to bite, what each carrier tends to "
                f"add, and what the instruments were reading.")
            if caught + missed:
                direction = (
                    f"they acted on {over_alert} bookings the world left alone and "
                    f"stayed quiet on {under_alert} it did not"
                    + (", which is the safer way round to be wrong"
                       if over_alert >= under_alert else
                       " - the more dangerous way round to be wrong, and worth"
                       " noting before trusting this calibration"))
                lines.append("")
                lines.append(
                    f"In exchange the rules caught {caught} of the {caught + missed} "
                    f"bookings that genuinely needed action, where \"always do "
                    f"nothing\" catches none. On this test set {direction}.")
            best_name = _best(action, "accuracy")
            best_table = action.get(best_name, {}).get("confusion")
            if best_name and best_name != "rules" and best_table and (caught + missed):
                best_caught = sum(best_table[t][p] for t in acted for p in acted)
                lines.append("")
                lines.append(
                    f"One number accuracy hides: of those {caught + missed} bookings "
                    f"that needed action, the rules moved on {caught} and "
                    f"{best_name} - the accuracy winner - moved on {best_caught}. "
                    f"A model can be right more often by acting rarely, and a "
                    f"policy can miss less by acting constantly; which error "
                    f"costs more is a desk decision, not a modelling one, so "
                    f"neither headline number settles the choice on its own.")

    delay = results["delay"]
    if "skipped" not in delay.get("gbm", {"skipped": True}) and "skipped" not in delay.get("mean", {"skipped": True}):
        lines.append("")
        lines.append(
            f"On \"how late will this booking actually run\", guessing the "
            f"historical average is off by {delay['mean']['mae_days']:.1f} days "
            f"on a typical booking; the best model is off by "
            f"{delay['gbm']['mae_days']:.1f}. That is the difference between a "
            f"number you can put in a customer email and one you cannot.")

    breach = results["breach"]
    if "skipped" not in breach.get("gbm", {"skipped": True}):
        auc = breach["gbm"]["roc_auc"]
        lines.append("")
        lines.append(
            f"On \"will the deadline break\", the best model's ROC-AUC is "
            f"{auc:.2f}: show it two bookings, one that will breach and one that "
            f"will not, and it puts the riskier one first {auc:.0%} of the time. "
            f"That ranking is what an approval queue would sort by, so the "
            f"person works the most urgent booking first.")

    lines += ["",
              "None of these numbers transfer to real freight. They show the "
              "PIPELINE works - features, split, baselines, honest labels - and "
              "they rank model families against each other inside a controlled "
              "world. The day real TMS history exists, this same harness runs "
              "unchanged and produces numbers that mean something operationally; "
              "until then, these stay in ml/reports/ and out of every page, "
              "pitch and demo.", ""]
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Evaluate every available backend against the synthetic world.")
    parser.add_argument("--data", default=str(DEFAULT_DATA),
                        help="dataset produced by python -m ml.synth")
    args = parser.parse_args()

    world = load_world(Path(args.data))
    print(f"Evaluating against {args.data} "
          f"({world['world']['bookings']} bookings, seed {world['world']['seed']})\n")
    report = evaluate(world)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    json_path = REPORTS_DIR / "evaluation.json"
    with open(json_path, "w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=1, ensure_ascii=False)
        handle.write("\n")
    md_path = REPORTS_DIR / "evaluation.md"
    with open(md_path, "w", encoding="utf-8") as handle:
        handle.write(render_markdown(report))

    print(f"\nWrote {json_path}")
    print(f"Wrote {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
