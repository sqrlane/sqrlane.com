"""ml/evaluate.py - the harness: three tasks, every backend that can run.

    python -m ml.evaluate
    python -m ml.evaluate --data ml/data/tms_synthetic_bookings.json

Reads the synthetic world, splits it BY TIME, trains every backend in
ml/models.py that has its dependencies, scores three tasks, and writes
ml/reports/evaluation.json and ml/reports/evaluation.md.

The split is the part that earns trust, so it is strict:

  * The first ~70% of the timeline trains, the rest tests - evaluation mimics
    predicting a future the model has not seen, which is the only future a
    deployed model ever gets. A random split would let the model train on
    Thursday's episode and be quizzed on Wednesday's.
  * No episode may straddle the boundary. Disruption episodes touch many
    bookings, and a model that saw three bookings caught in a strike would be
    scored on the fourth booking in the SAME strike - memorisation dressed as
    prediction. Bookings tangled in a boundary-straddling episode are dropped,
    the report says how many, and the harness ASSERTS the train and test
    episode sets are disjoint.

Backends whose dependencies are missing are skipped with the reason printed
and recorded - here, tabpfn skips (no torch, and the weights download is
blocked); on a machine without scikit-learn, the sklearn rows skip too and
the stdlib baselines plus the shipped rules engine still report.

Metrics are implemented in the standard library on purpose, so a zero-install
machine can still score the baselines: accuracy, macro-F1 and a confusion
table for the action model; MAE and P90 absolute error for the delay model;
ROC-AUC (rank-based) and the Brier score for the breach model.

And the part that must never get lost: every number this file produces is a
score against a SYNTHETIC world - see the preamble it writes at the top of
both reports. The numbers say nothing about real freight and must never
appear on the product pages.
"""

import argparse
import json
from pathlib import Path

from ml import models

REPORTS_DIR = Path(__file__).resolve().parent / "reports"
DEFAULT_DATA = Path(__file__).resolve().parent / "data" / "tms_synthetic_bookings.json"

TRAIN_FRACTION = 0.7

# Written verbatim at the top of both reports. If you are editing this, you
# are probably about to make a claim the project cannot back - read
# ml/README.md first.
HONESTY_PREAMBLE = (
    "EVERY NUMBER IN THIS REPORT IS SYNTHETIC-WORLD PERFORMANCE. The dataset "
    "is generated by ml/synth.py: bookings, disruptions and outcomes all come "
    "from a structural model with latent variables and noise, and the labels "
    "are the generator's realized outcomes - not any policy's opinion, and "
    "not real freight history. A model scored here has learned the simulated "
    "world, nothing more. These numbers say NOTHING about accuracy on real "
    "shipments - that would need real TMS history, which sits on the far side "
    "of the integration wall - and they must NEVER appear on the product "
    "pages (static/), in the README's pitch, or in any demo narration. They "
    "exist to compare model families against each other and against the "
    "shipped rules engine, inside a world we control end to end."
)


# ---------------------------------------------------------------------------
# Loading and the time split
# ---------------------------------------------------------------------------


def load_world(path: Path) -> dict:
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except FileNotFoundError:
        raise SystemExit(
            f"No dataset at {path}.\n"
            f"Generate one first:  python -m ml.synth --bookings 6000 --seed 7")


def split_by_time(world: dict):
    """Train on the early world, test on the late one, drop the tangled edge.

    Returns (train, test, info). Every record keeps its outcome block here -
    the harness needs it for labels - and it is stripped before records are
    handed to any model.
    """
    bookings = sorted(world["bookings"], key=lambda b: (b["facts"]["decided_on"], b["id"]))
    decided = [b["facts"]["decided_on"] for b in bookings]
    # The cut sits 70% of the way through the DECISION timeline, day-wise,
    # so it is a date in the world - not an index into the book - and the
    # same cut applies to bookings and episodes alike.
    cut_date = decided[min(len(decided) - 1, round(len(decided) * TRAIN_FRACTION))]

    episode_side = {e["episode_id"]: ("train" if e["started_on"] < cut_date else "test")
                    for e in world["episodes"]}

    train, test, dropped = [], [], 0
    for booking in bookings:
        sides = {episode_side[e["episode_id"]]
                 for e in booking["facts"]["active_episodes"]}
        booking_side = "train" if booking["facts"]["decided_on"] < cut_date else "test"
        if sides and sides != {booking_side}:
            # This booking is tangled in an episode that lives on the other
            # side of the cut. Scoring it would leak the episode across the
            # boundary, so it sits the evaluation out.
            dropped += 1
            continue
        (train if booking_side == "train" else test).append(booking)

    train_episodes = {e["episode_id"] for b in train
                      for e in b["facts"]["active_episodes"]}
    test_episodes = {e["episode_id"] for b in test
                     for e in b["facts"]["active_episodes"]}
    straddlers = train_episodes & test_episodes
    assert not straddlers, (
        f"Episodes straddle the time split: {sorted(straddlers)} - the split "
        f"is leaking, and every score it produces is inflated.")

    info = {"cut_date": cut_date, "train": len(train), "test": len(test),
            "dropped_straddling_bookings": dropped,
            "train_episodes": len(train_episodes), "test_episodes": len(test_episodes)}
    return train, test, info


def strip_outcomes(records):
    """What models are allowed to see: the booking without its answer key."""
    return [{k: v for k, v in r.items() if k != "outcome"} for r in records]


# ---------------------------------------------------------------------------
# Metrics - stdlib on purpose, so the baselines score with zero installs
# ---------------------------------------------------------------------------


def accuracy(y_true, y_pred):
    return sum(1 for t, p in zip(y_true, y_pred) if t == p) / len(y_true)


def macro_f1(y_true, y_pred):
    labels = sorted(set(y_true) | set(y_pred))
    scores = []
    for label in labels:
        tp = sum(1 for t, p in zip(y_true, y_pred) if t == label and p == label)
        fp = sum(1 for t, p in zip(y_true, y_pred) if t != label and p == label)
        fn = sum(1 for t, p in zip(y_true, y_pred) if t == label and p != label)
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        scores.append(2 * precision * recall / (precision + recall)
                      if precision + recall else 0.0)
    return sum(scores) / len(scores)


def confusion(y_true, y_pred, labels):
    return {t: {p: sum(1 for a, b in zip(y_true, y_pred) if a == t and b == p)
                for p in labels}
            for t in labels}


def mae(y_true, y_pred):
    return sum(abs(t - p) for t, p in zip(y_true, y_pred)) / len(y_true)


def p90_abs_error(y_true, y_pred):
    errors = sorted(abs(t - p) for t, p in zip(y_true, y_pred))
    return errors[min(len(errors) - 1, round(0.9 * (len(errors) - 1)))]


def roc_auc(y_true, scores):
    """Rank-based AUC (the Mann-Whitney statistic), ties averaged. Returns
    None when the test set has only one class - an AUC of nothing is more
    honest than a made-up 0.5."""
    positives = sum(y_true)
    negatives = len(y_true) - positives
    if not positives or not negatives:
        return None
    order = sorted(range(len(scores)), key=lambda i: scores[i])
    ranks = [0.0] * len(scores)
    index = 0
    while index < len(order):
        tied_end = index
        while (tied_end + 1 < len(order)
               and scores[order[tied_end + 1]] == scores[order[index]]):
            tied_end += 1
        average_rank = (index + tied_end) / 2 + 1
        for position in range(index, tied_end + 1):
            ranks[order[position]] = average_rank
        index = tied_end + 1
    positive_rank_sum = sum(r for r, t in zip(ranks, y_true) if t)
    return (positive_rank_sum - positives * (positives + 1) / 2) / (positives * negatives)


def brier(y_true, scores):
    return sum((s - t) ** 2 for t, s in zip(y_true, scores)) / len(y_true)


# ---------------------------------------------------------------------------
# The run
# ---------------------------------------------------------------------------


def score(task, y_true, y_pred):
    if task == "action":
        return {"accuracy": round(accuracy(y_true, y_pred), 4),
                "macro_f1": round(macro_f1(y_true, y_pred), 4),
                "confusion": confusion(y_true, y_pred, models.ACTION_LABELS)}
    if task == "delay":
        return {"mae_days": round(mae(y_true, y_pred), 3),
                "p90_abs_error_days": round(p90_abs_error(y_true, y_pred), 3)}
    auc = roc_auc(y_true, y_pred)
    return {"roc_auc": round(auc, 4) if auc is not None else None,
            "brier": round(brier(y_true, y_pred), 4)}


def _environment() -> dict:
    """Recorded in the report because the sklearn numbers can shift across
    releases even though the dataset itself is byte-reproducible per seed."""
    import platform
    env = {"python": platform.python_version()}
    try:
        import sklearn
        env["scikit_learn"] = sklearn.__version__
    except ImportError:
        env["scikit_learn"] = None
    return env


def evaluate(world: dict) -> dict:
    train, test, split_info = split_by_time(world)
    train_visible = strip_outcomes(train)
    test_visible = strip_outcomes(test)

    results = {}
    for task, registry in models.MODELS.items():
        y_train = [models.target_for(task, r) for r in train]
        y_test = [models.target_for(task, r) for r in test]
        results[task] = {}
        for name, factory in registry.items():
            try:
                model = factory()
            except models.DependencyMissing as exc:
                print(f"[{task}] {name}: SKIPPED - {str(exc).splitlines()[0]}")
                results[task][name] = {"skipped": str(exc)}
                continue
            model.fit(train_visible, y_train)
            predictions = model.predict(test_visible)
            results[task][name] = score(task, y_test, predictions)
            headline = {k: v for k, v in results[task][name].items() if k != "confusion"}
            print(f"[{task}] {name}: {headline}")
    return {"honesty": HONESTY_PREAMBLE, "world": world["world"],
            "split": split_info, "environment": _environment(),
            "results": results}


